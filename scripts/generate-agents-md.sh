#!/usr/bin/env bash
# Rebuild AGENTS.md from its two sources:
#   AGENTS.project.md  — the project section (ours)
#   ponytail.md        — the exact upstream Ponytail copy
# Pure concatenation; no filtering. The self-reference line in ponytail.md
# stays (John, Nov 8 2026: "it doesn't much matter").
#
# Usage: scripts/generate-agents-md.sh [<upstream-sha>]
#   <upstream-sha> goes in the header comment; defaults to the SHA recorded
#   in the current AGENTS.md header, or "unknown" if there is none.
# Run from the repo root.
set -euo pipefail

cd "$(dirname "$0")/.."

SHA="${1:-}"
if [ -z "$SHA" ] && [ -f AGENTS.md ]; then
    SHA="$(sed -n 's/.*ponytail @ \([0-9a-f]*\).*/\1/p' AGENTS.md | head -1)"
fi
SHA="${SHA:-unknown}"

{
    echo "<!-- Ponytail AGENTS.md — source: DietrichGebert/ponytail @ ${SHA}, MIT, https://github.com/DietrichGebert/ponytail — generated by scripts/generate-agents-md.sh, do not edit directly -->"
    echo
    cat AGENTS.project.md
    cat ponytail.md
} > AGENTS.md

echo "AGENTS.md rebuilt from AGENTS.project.md + ponytail.md (upstream @ ${SHA})."
